#!/usr/bin/env python3
"""Keep external skills in step with external/registry.json.

Prototype for discussion. Every external skill we consider is a `sources` entry in the registry,
with a status:

  evaluating  someone is trialling it on their own machine; nothing is in the repo
  mirrored    an UNMODIFIED copy lives in plugins/<plugin>/skills/<name>/, with the upstream
              LICENSE and UPSTREAM.json (repo, commit, file checksums)
  absorbed    we took specific rules into our own skills (listed in `absorbed_into`); upstream
              is a source of ideas, not a dependency
  rejected    recorded with a reason so nobody re-evaluates it from scratch

Commands
  verify                    fail if any mirrored copy differs from its UPSTREAM.json checksums
                            (mirrors are never edited by hand)
  check [--apply] --out DIR for each mirrored/absorbed source whose upstream branch has moved:
                            mirrored + --apply -> refresh the copy, UPSTREAM.json, plugin version
                            and registry commit; writes DIR/mirrored.md for the sync PR
                            absorbed -> writes DIR/absorbed-<id>.md for a "review for new ideas"
                            issue (the registry commit moves only when a person closes it)
  mirror <id>               create or refresh one mirror now (used when a source is first adopted)

Uses only git and the standard library. Upstream files are copied, never executed.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "external" / "registry.json"


def git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def load() -> dict:
    return json.loads(REGISTRY.read_text())


def save(reg: dict) -> None:
    REGISTRY.write_text(json.dumps(reg, indent=2) + "\n")


def upstream_head(src: dict) -> str:
    out = git("ls-remote", src["repo"], f"refs/heads/{src.get('branch', 'main')}")
    if not out:
        raise SystemExit(f"{src['id']}: branch {src.get('branch', 'main')} not found at {src['repo']}")
    return out.split()[0]


def checksums(folder: Path) -> dict[str, str]:
    return {
        p.relative_to(folder).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(folder.rglob("*"))
        if p.is_file()
    }


def skill_dir(src: dict) -> Path:
    return ROOT / "plugins" / src["plugin"] / "skills" / Path(src["path"]).name


def mirror(src: dict, sha: str) -> str:
    """Copy upstream `path` at `sha` into the plugin, unmodified. Returns the commit date."""
    with tempfile.TemporaryDirectory() as tmp:
        clone = Path(tmp) / "upstream"
        git("clone", "--quiet", "--filter=blob:none", "--no-checkout", src["repo"], str(clone))
        git("checkout", "--quiet", sha, cwd=clone)
        date = git("log", "-1", "--format=%cs", cwd=clone)
        source = clone / src["path"]
        if not (source / "SKILL.md").is_file():
            raise SystemExit(f"{src['id']}: {src['path']}/SKILL.md not found at {sha[:12]}")
        target = skill_dir(src)
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(source, target)
        plugin_root = ROOT / "plugins" / src["plugin"]
        for name in ("LICENSE", "LICENSE.md", "LICENSE.txt", "NOTICE"):
            if (clone / name).is_file():
                shutil.copy2(clone / name, plugin_root / name)
    plugin_root = ROOT / "plugins" / src["plugin"]
    (plugin_root / "UPSTREAM.json").write_text(json.dumps({
        "repo": src["repo"], "path": src["path"], "commit": sha, "commit_date": date,
        "license": src.get("license"), "note": "Generated by scripts/external_skills.py. Do not edit the mirrored files.",
        "files": checksums(target),
    }, indent=2) + "\n")
    manifest = plugin_root / ".claude-plugin" / "plugin.json"
    data = json.loads(manifest.read_text())
    data["version"] = f"{date.replace('-', '.')}-{sha[:7]}"
    manifest.write_text(json.dumps(data, indent=2) + "\n")
    src["sha"] = sha
    return date


def verify(reg: dict) -> int:
    bad = 0
    for src in reg["sources"]:
        if src["status"] != "mirrored":
            continue
        meta_path = ROOT / "plugins" / src["plugin"] / "UPSTREAM.json"
        if not meta_path.is_file():
            print(f"ERROR  {src['id']}: {meta_path.relative_to(ROOT)} is missing"); bad += 1; continue
        meta = json.loads(meta_path.read_text())
        if meta["commit"] != src["sha"]:
            print(f"ERROR  {src['id']}: registry sha {src['sha'][:12]} != UPSTREAM.json {meta['commit'][:12]}"); bad += 1
        actual = checksums(skill_dir(src))
        for path in sorted(set(meta["files"]) | set(actual)):
            if meta["files"].get(path) != actual.get(path):
                state = "added" if path not in meta["files"] else "missing" if path not in actual else "edited"
                print(f"ERROR  {src['id']}: {path} {state}; mirrors must match upstream. "
                      f"Put NFN changes in our own skills, or change the source's status to absorbed.")
                bad += 1
    topics = reg.get("topics", {})
    for src in reg["sources"]:
        owner = topics.get(src.get("topic"))
        if src["status"] == "mirrored" and owner != src["plugin"]:
            print(f"ERROR  {src['id']}: topic {src.get('topic')!r} is owned by {owner!r}; "
                  f"a mirror may only cover a topic it owns"); bad += 1
    print(f"external skills: {bad} problem(s)")
    return 1 if bad else 0


def check(reg: dict, apply: bool, out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    mirrored_lines = []
    for src in reg["sources"]:
        if src["status"] not in ("mirrored", "absorbed"):
            continue
        head = upstream_head(src)
        if head == src["sha"]:
            print(f"{src['id']}: up to date at {head[:12]}")
            continue
        compare = f"{src['repo'].removesuffix('.git')}/compare/{src['sha']}...{head}"
        print(f"{src['id']}: upstream moved {src['sha'][:12]} -> {head[:12]}")
        if src["status"] == "mirrored":
            if apply:
                old = src["sha"]
                date = mirror(src, head)
                mirrored_lines.append(f"- **{src['id']}** → `plugins/{src['plugin']}`: {old[:12]} → {head[:12]} "
                                      f"(committed {date}). [Upstream compare]({compare})")
        else:
            body = [
                f"Upstream `{src['repo']}` (`{src['path']}`) moved from {src['sha'][:12]} to {head[:12]}.",
                "", f"[Compare upstream changes]({compare})", "",
                "We absorbed rules from this source into:", "",
                *[f"- `{p}`" for p in src.get("absorbed_into", [])], "",
                "Review the upstream diff for anything worth taking. Then update `sha` for this source "
                "in `external/registry.json` to the new commit (in the same PR as any rule changes, "
                "or on its own if nothing was taken) and close this issue.",
            ]
            (out / f"absorbed-{src['id']}.md").write_text("\n".join(body) + "\n")
    if apply and mirrored_lines:
        save(reg)
    (out / "mirrored.md").write_text("\n".join(mirrored_lines) + ("\n" if mirrored_lines else ""))
    return 0


def main(argv: list[str]) -> int:
    reg = load()
    if not argv or argv[0] not in ("verify", "check", "mirror"):
        print(__doc__); return 2
    if argv[0] == "verify":
        return verify(reg)
    if argv[0] == "check":
        out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else Path(tempfile.mkdtemp())
        return check(reg, "--apply" in argv, out)
    src = next((s for s in reg["sources"] if s["id"] == argv[1]), None)
    if not src:
        raise SystemExit(f"no source {argv[1]!r} in {REGISTRY.relative_to(ROOT)}")
    sha = argv[2] if len(argv) > 2 else upstream_head(src)
    mirror(src, sha)
    save(reg)
    print(f"{src['id']}: mirrored {sha[:12]} into plugins/{src['plugin']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
